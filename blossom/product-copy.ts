export function productCopy(product: Product, lang: Language) {
  const localized = copy[product.id]?.[lang];
  return localized ?? { title: product.name[lang], description: product.description[lang], keywords: undefined };
}

const sizeLabels: Record<string, Pick<Record<Language, string>, 'th' | 'zh'>> = {
  Queen: { th: 'ควีนไซซ์', zh: '大号（Queen）' },
  King: { th: 'คิงไซซ์', zh: '特大号（King）' },
};

export function productSize(size: string, lang: Language) {
  return lang === 'en' ? size : sizeLabels[size]?.[lang] ?? size;
}
